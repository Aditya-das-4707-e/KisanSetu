const DICTS = { en, hi, bn };

function fill(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined ? vars[k] : `{${k}}`
  );
}

const LangCtx = createContext({ lang: "en", setLang: () => {} });

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === "hi" || saved === "bn" || saved === "en") return saved;
    } catch {
      /* ignore */
    }
    return "en";
  });

  function setLang(code) {
    setLangState(code);
    try {
      localStorage.setItem(LANG_KEY, code);
    } catch {
      /* ignore */
    }
  }

  useEffect(() => {
    document.documentElement.lang = lang === "hi" ? "hi" : lang === "bn" ? "bn" : "en";
  }, [lang]);

  return <LangCtx.Provider value={{ lang, setLang }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  const { lang, setLang } = useContext(LangCtx);
  const dict = DICTS[lang] || en;

  function t(key, vars) {
    const template = dict[key] ?? en[key] ?? key;
    return vars ? fill(template, vars) : template;
  }

  function cropName(crop) {
    if (!crop) return "";
    if (typeof crop === "string") return CROP_NAMES[crop]?.[lang] ?? crop;
    return CROP_NAMES[crop.id]?.[lang] ?? crop.name;
  }

  function cropLocal(crop) {
    if (!crop) return "";
    if (typeof crop === "string") return CROP_LOCAL[crop]?.[lang] ?? crop;
    return CROP_LOCAL[crop.id]?.[lang] ?? crop.local;
  }

  function categoryName(cat) {
    return CATEGORY_NAMES[cat]?.[lang] ?? cat;
  }

  function unitName(unit) {
    return UNIT_NAMES[unit]?.[lang] ?? unit;
  }

  function fmtUpdated(minsAgo) {
    if (minsAgo < 60) return t("time.mAgo", { n: minsAgo });
    return t("time.hAgo", { n: Math.round(minsAgo / 60) });
  }

  /** Field validation rules with translated messages (run via validateValues). */
  function validators() {
    return {
      required: (v) => String(v ?? "").trim().length > 0 || t("err.required"),
      email: (v) =>
        /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(v ?? "")) || t("err.email"),
      phone: (v) =>
        /^[6-9]\d{9}$/.test(String(v ?? "").replace(/\D/g, "").slice(-10)) ||
        t("err.phone"),
      minAge: (min) => (v) => Number(v) >= min || t("err.minAge", { min }),
      minLength: (min) => (v) =>
        String(v ?? "").length >= min || t("err.minLength", { min }),
      matches: (otherValue, label) => (v) => v === otherValue || t("err.matches", { label }),
    };
  }

  return { lang, setLang, t, cropName, cropLocal, categoryName, unitName, fmtUpdated, validators };
}
